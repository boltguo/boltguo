import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

// Use the image encoder already installed with Astro.
const sharp = createRequire(import.meta.resolve('astro'))('sharp');
const root = new URL('../', import.meta.url);
const sources = [
  ['kotoplanet', 'kotoplanet.png'],
  ['luti', 'luti.png'],
  ['codepin', 'codepin-40.png'],
  ['anya-codex-pet', 'anya-codex-pet.png'],
];
const gutter = 2;
// 16 CSS pixels at up to 3× pixel density.
const iconSize = 48;
const icons = [];
let width = 0;
let height = 0;
let sourceBytes = 0;

for (const [name, filename] of sources) {
  const source = await readFile(
    new URL(`scripts/assets/project-icons/${filename}`, root)
  );
  const { data, info } = await sharp(source)
    .resize(iconSize, iconSize, {
      fit: 'contain',
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  // RGB values underneath fully transparent pixels have no visible effect.
  for (let pixel = 0; pixel < data.length; pixel += 4) {
    if (data[pixel + 3] === 0) data.fill(0, pixel, pixel + 3);
  }
  icons.push({ name, data, ...info, x: gutter, y: height + gutter });
  width = Math.max(width, info.width + gutter * 2);
  height += info.height + gutter * 2;
  sourceBytes += source.length;
}

// Pack the normalized RGBA pixels without any additional blending.
const pixels = Buffer.alloc(width * height * 4);
for (const icon of icons) {
  for (let row = 0; row < icon.height; row++) {
    icon.data.copy(
      pixels,
      ((icon.y + row) * width + icon.x) * 4,
      row * icon.width * 4,
      (row + 1) * icon.width * 4
    );
  }
}
const sprite = await sharp(pixels, { raw: { width, height, channels: 4 } })
  .webp({ lossless: true, effort: 6 })
  .toBuffer();

// Verify visible colors and alpha; WebP may change RGB under zero alpha.
for (const icon of icons) {
  const decoded = await sharp(sprite)
    .extract({
      left: icon.x,
      top: icon.y,
      width: icon.width,
      height: icon.height,
    })
    .raw()
    .toBuffer();
  for (let pixel = 0; pixel < decoded.length; pixel += 4) {
    if (decoded[pixel + 3] === 0) decoded.fill(0, pixel, pixel + 3);
  }
  if (!decoded.equals(icon.data)) {
    throw new Error(`Sprite pixels changed for ${icon.name}`);
  }
}

const em = (value) => `${Number(value.toFixed(8))}em`;
const css = [
  '/* Generated by scripts/build-project-sprite.mjs. */',
  '.project-sprite {',
  '  display: block;',
  '  width: 1em;',
  '  height: 1em;',
  "  background-image: url('/icons/projects/project-sprite.webp');",
  '  background-repeat: no-repeat;',
  `  background-size: ${em(width / iconSize)} ${em(height / iconSize)};`,
  '}',
  ...icons.map((icon) => {
    return `\n.project-sprite--${icon.name} {\n  background-position: ${em(-icon.x / iconSize)} ${em(-icon.y / iconSize)};\n}`;
  }),
  '',
].join('\n');

await mkdir(new URL('public/icons/projects/', root), { recursive: true });
await writeFile(
  new URL('public/icons/projects/project-sprite.webp', root),
  sprite
);
await writeFile(new URL('src/styles/project-sprite.css', root), css);
console.log(
  `4 PNGs (${sourceBytes} bytes) → 1 lossless WebP (${sprite.length} bytes, ${width}×${height}); normalized pixels verified.`
);
